/** Legacy saved OT records are readable, but OT is never a selectable country. */
export function countryLabel(code: string): string {
  if (code === 'OT') return 'Country not specified';
  try {
    const name = new Intl.DisplayNames(['en'], { type: 'region' }).of(code);
    if (name && name !== code) return name;
  } catch {
    // Use the English ISO name on browsers without Intl.DisplayNames.
  }
  return COUNTRY_NAMES[code] ?? code;
}

export const COUNTRY_CODES = Object.keys(COUNTRY_NAMES).sort((a, b) =>
  countryLabel(a).localeCompare(countryLabel(b), 'en')
);
