const Icon: React.FC<IconProps> = ({
  name,
  type = 'Line',
  size = 20,
  className,
}) => {
  const iconName = type !== 'NIL' ? `${name}${type}` : name;

  const DynamicIcon = Object.prototype.hasOwnProperty.call(RemixIcons, iconName)
    ? RemixIcons[iconName as keyof typeof RemixIcons]
    : undefined;

  if (!DynamicIcon) {
    console.error(`Icon "${iconName}" does not exist in RemixIcons.`);
    return null;
  }

  return <DynamicIcon className={className} size={size} />;
};

export default Icon;
