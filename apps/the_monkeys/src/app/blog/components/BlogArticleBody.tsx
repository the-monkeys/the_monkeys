'use client';

import { createContext, createElement, useContext } from 'react';

import dynamic from 'next/dynamic';

import { articleAnchor, articleImageAlt } from '@/lib/articleAnnotations';
import type { OutputData } from '@themonkeys/monkeys-editor';
import DOMPurify from 'isomorphic-dompurify';

const ArticleData = createContext<OutputData | undefined>(undefined);

const text = (value: unknown) => (typeof value === 'string' ? value : '');
const record = (value: unknown): Record<string, unknown> =>
  value && typeof value === 'object' ? (value as Record<string, unknown>) : {};
const array = (value: unknown): unknown[] =>
  Array.isArray(value) ? value : [];

// Use the same isomorphic sanitizer as the editor's Markdown preview. Only
// inline formatting is allowed here; block structure is generated by React.
function inline(value: unknown) {
  return {
    __html: DOMPurify.sanitize(text(value), {
      ALLOWED_TAGS: [
        'b',
        'strong',
        'i',
        'em',
        'u',
        's',
        'a',
        'code',
        'br',
        'mark',
        'sub',
        'sup',
      ],
      ALLOWED_ATTR: ['href', 'title'],
    }),
  };
}

function safeUrl(value: unknown) {
  const url = text(value).trim();
  return /^(https?:\/\/|\/(?!\/))[^\s\\]*$/i.test(url) ? url : undefined;
}

function list(
  items: unknown,
  ordered: boolean,
  nested = false
): React.ReactNode {
  return createElement(
    ordered ? 'ol' : 'ul',
    { className: nested ? 'cdx-list__sublist' : 'cdx-list' },
    array(items).map((item, index) => {
      const data = record(item);
      return (
        <li key={index} className='cdx-list__item'>
          <div
            className='cdx-list__item-content'
            dangerouslySetInnerHTML={inline(
              typeof item === 'string' ? item : data.content
            )}
          />
          {array(data.items).length > 0 && list(data.items, ordered, true)}
        </li>
      );
    })
  );
}

function blockContent(type: string, data: Record<string, unknown>) {
  switch (type) {
    case 'title':
    case 'header': {
      const level = Number(data.level);
      const heading =
        Number.isInteger(level) && level >= 1 && level <= 6 ? level : 2;
      return createElement(`h${heading}`, {
        className: 'ce-header',
        id: articleAnchor(data.anchor),
        style: articleAnchor(data.anchor)
          ? { scrollMarginTop: '8rem' }
          : undefined,
        dangerouslySetInnerHTML: inline(data.text),
      });
    }
    case 'paragraph':
    case 'mention':
      return (
        <p
          className='ce-paragraph'
          dangerouslySetInnerHTML={inline(data.text)}
        />
      );
    case 'list':
      return list(data.items, data.style === 'ordered');
    case 'quote':
      return (
        <blockquote className='cdx-quote'>
          <p
            className='cdx-quote__text'
            dangerouslySetInnerHTML={inline(data.text)}
          />
          <cite
            className='cdx-quote__caption'
            dangerouslySetInnerHTML={inline(data.caption)}
          />
        </blockquote>
      );
    case 'code':
      return (
        <pre className='overflow-x-auto'>
          <code>{text(data.code)}</code>
        </pre>
      );
    case 'table':
      return (
        <div className='overflow-x-auto'>
          <table>
            <tbody>
              {array(data.content).map((row, rowIndex) => (
                <tr key={rowIndex}>
                  {array(row).map((cell, cellIndex) =>
                    createElement(
                      data.withHeadings && rowIndex === 0 ? 'th' : 'td',
                      { key: cellIndex, dangerouslySetInnerHTML: inline(cell) }
                    )
                  )}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      );
    case 'image': {
      const url = safeUrl(record(data.file).url);
      return (
        <figure className='image-tool'>
          {url && (
            // Match the editor's ordinary image element, without adding an image proxy.
            // eslint-disable-next-line @next/next/no-img-element
            <img
              src={url}
              alt={articleImageAlt(data)}
              className='image-tool__image-picture max-w-full'
            />
          )}
          <figcaption
            className='image-tool__caption'
            dangerouslySetInnerHTML={inline(data.caption)}
          />
        </figure>
      );
    }
    case 'delimiter':
      return <hr className='ce-delimiter' />;
    case 'embed': {
      const url = safeUrl(data.url);
      return url ? <a href={url}>{url}</a> : null;
    }
    case 'markdown':
      // The existing editor adds the full Markdown preview after hydration.
      return (
        <div className='ce-paragraph whitespace-pre-wrap'>
          {text(data.markdown)}
        </div>
      );
    default: {
      // Custom data/research blocks retain readable text before their existing
      // interactive charts, formulae, and controls are mounted by the editor.
      const fields = [
        'title',
        'text',
        'summary',
        'expression',
        'description',
        'citationText',
        'authors',
        'year',
        'source',
        'identifier',
        'studyDesign',
        'dataCollection',
        'analysisMethod',
        'assumptions',
        'limitations',
        'sampleSize',
        'collectionDate',
        'license',
        'variables',
        'notes',
      ];
      return fields.map(
        (field) =>
          typeof data[field] === 'string' && (
            <p key={field} className='ce-paragraph'>
              {text(data[field])}
            </p>
          )
      );
    }
  }
}

/** Visible HTML for SSR/no-JS and while the existing editor chunk is loading. */
export function ArticleBodyFallback({ data }: { data?: OutputData }) {
  if (!data?.blocks?.length) return null;
  return (
    <div className='mx-auto px-4 break-words' data-article-body>
      {data.blocks.map((block, index) => (
        <div key={block.id ?? index} className='ce-block'>
          <div className='ce-block__content'>
            {blockContent(block.type, record(block.data))}
          </div>
        </div>
      ))}
    </div>
  );
}

function ArticleBodyLoading() {
  return <ArticleBodyFallback data={useContext(ArticleData)} />;
}

const Editor = dynamic(() => import('@/components/editor/preview'), {
  ssr: false,
  loading: ArticleBodyLoading,
});

export function BlogArticleBody({ data }: { data?: OutputData }) {
  return (
    <ArticleData.Provider value={data}>
      <Editor data={data} />
    </ArticleData.Provider>
  );
}
